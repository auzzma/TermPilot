export function useTranslation() {
  const language = useAppStore((state) => state.preferences.language);
  const chinese =
    language === "zh-Hans" ||
    (language === "system" && navigator.language.toLowerCase().startsWith("zh"));
  return (value: string) => (chinese ? (zhHans[value] ?? value) : value);
}
