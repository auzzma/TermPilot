#!/usr/bin/env python3
"""Generate native constants from the shared mobile UI specification (build time only)."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
spec = json.loads((root / "apps/mobile/design/tokens.json").read_text())
banner = "// Generated by scripts/mobile/generate-design.py; edit apps/mobile/design/tokens.json.\n"
kotlin = banner + "package com.termpilot.app\n\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\n\nobject MobileDesign {\n"
swift = banner + "import SwiftUI\n\nenum MobileDesign {\n"
for name, value in spec["metrics"].items():
    kotlin += f"    val {name} = {value}.dp\n"
    swift += f"  static let {name}: CGFloat = {value}\n"
for theme in ("light", "dark"):
    kotlin += f"    object {theme.title()} {{\n"
    swift += f"  enum {theme.title()} {{\n"
    for name, value in spec[theme].items():
        kotlin += f"        val {name} = Color(0xff{value.lower()})\n"
        rgb = [int(value[i:i+2], 16) for i in (0, 2, 4)]
        swift += f"    static let {name} = Color(red: {rgb[0]}.0 / 255, green: {rgb[1]}.0 / 255, blue: {rgb[2]}.0 / 255)\n"
    kotlin += "    }\n"
    swift += "  }\n"
kotlin += "}\n"
swift += "}\n"
outputs = {
    "apps/android/app/src/main/java/com/termpilot/app/MobileDesignTokens.kt": kotlin,
    "apps/ios/Sources/MobileDesignTokens.swift": swift,
}
check = argparse.ArgumentParser()
check.add_argument("--check", action="store_true")
args = check.parse_args()
for name, content in outputs.items():
    path = root / name
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"Out-of-date design constants: {name}")
    else:
        path.write_text(content)
    print(name)
